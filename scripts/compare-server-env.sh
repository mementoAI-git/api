#!/usr/bin/env bash
# Compares the dev and prod API settings on the server and prints only what
# differs. Behaviour settings show their values; keys, URLs and IDs show only
# whether they are set. Keys that exist in one file only are listed by name.
# Usage: compare-server-env.sh /opt/memento/backend-dev/.env /opt/memento/backend-prod/.env
set -euo pipefail
DEV_FILE="$1"; PROD_FILE="$2"

VALUE_KEYS="
AI_SLO_ERROR_RATE_MAX AI_SLO_FALLBACK_RATE_MAX AI_SLO_P95_LATENCY_MS_MAX APPLE_IAP_NOTIFICATIONS_ENABLED ASR_FALLBACK_PROVIDER ASR_GEMINI_FALLBACK_MODEL ASR_GEMINI_PRIMARY_MODEL ASR_PROVIDER ASR_SHADOW_ENABLED ASR_SHADOW_PROVIDER BULL_BOARD_ENABLED CHAT_LOOKUPS_ENABLED CHOOSER CLOUDINARY_CLOUD_NAME CORS_ALLOWED_ORIGINS DEEPSEEK_MODEL_CHAT_FALLBACK DEEPSEEK_MODEL_CHAT_PRIMARY EMBEDDING_CACHE_DIR EMBEDDING_PROVIDER EVAL_SPACING_MS FEATURE_FLAG_ENVIRONMENT FFMPEG_PATH FFPROBE_PATH FILE_URL_TTL_SECONDS GEMINI_LIVE_MODEL_VERSION GEMINI_MODEL_VERSION GEMINI_TTS_MODEL_VERSION GOOGLE_PLAY_RTDN_ENABLED GROQ_FAST_MODE_ENABLED GROQ_FAST_MODE_MAX_INPUT_CHARS GROQ_MODEL_CHAT_FALLBACK GROQ_MODEL_CHAT_FAST_FALLBACK GROQ_MODEL_CHAT_FAST_PRIMARY GROQ_MODEL_CHAT_PRIMARY GROQ_MODEL_CHAT_TOOLS JSON_BODY_LIMIT MASTERS_DIR MAX_UPLOAD_FILES MEMENTO_ENV MEMORY_RETRIEVAL MEMORY_SEARCH_DIGUP_PATH MEMORY_SEARCH_ENABLED MEMORY_SEARCH_MODELS_DIR MEMORY_SEARCH_PHOTOS_ENABLED OPENROUTER_APP_NAME OPENROUTER_CRITICAL_ENABLED OR_MODEL_CHAT_FALLBACK OR_MODEL_CHAT_PRIMARY OR_MODEL_TAGS_FALLBACK OR_MODEL_TAGS_PRIMARY OR_MODEL_TRANSCRIPTION_FALLBACK OR_MODEL_TRANSCRIPTION_PRIMARY POLAR_PRODUCT_LEGACY_ANNUAL POLAR_PRODUCT_LEGACY_LIFETIME POLAR_PRODUCT_LEGACY_MONTHLY POLAR_PRODUCT_PRO_ANNUAL POLAR_PRODUCT_PRO_MONTHLY PROMPT_VERSION_CHAT_BOOTSTRAP PROMPT_VERSION_CHAT_PRIMARY PROMPT_VERSION_ONBOARDING_CHAT PROMPT_VERSION_TAGS_GENERATE PROMPT_VERSION_TRANSCRIPTION SENTRY_TUNNEL_ALLOWED_HOSTS SENTRY_TUNNEL_ENABLED SENTRY_TUNNEL_MAX_BYTES SENTRY_TUNNEL_RATE_LIMIT_PER_MINUTE SENTRY_TUNNEL_TIMEOUT_MS STAFF_ORIGIN STAGING_AUTO_PRO STORAGE_LIMIT_FREE_BYTES STORAGE_LIMIT_LEGACY_BYTES STORAGE_LIMIT_PRO_BYTES STORAGE_RESERVATION_TTL_SECONDS TALLY_WEBHOOK_ENABLED TALLY_WEBHOOK_RATE_LIMIT_PER_MINUTE TEMP_PATH TMPDIR UPLOAD_FILE_SIZE_LIMIT_MB VOICE_MAX_CALL_MINUTES VOICE_PROBE_DEBUG VOICE_PROBE_ONLY VOICE_PROBE_SCHEDULING VOICE_PROVIDER_DEFAULT VOICE_SPEAKER_DUPLEX_DENYLIST VOICE_TURN_AB_PERCENT WEBAUTHN_ORIGIN WEBAUTHN_ORIGINS WEBAUTHN_RP_NAME "
PRESENCE_KEYS="MEMORY_SEARCH_ENGINE_URL MEMORY_SEARCH_USER_IDS ELEVENLABS_BASE_URL SUPERMEMORY_API_KEY ELEVENLABS_API_KEY GROQ_API_KEY OPENROUTER_API_KEY DEEPSEEK_API_KEY CLOUDFLARE_AI_API_KEY GEMINI_API_KEY GEMINI_API_KEY_ALT GOOGLE_PLAY_SERVICE_ACCOUNT_KEY IAP_TOKEN_ENCRYPTION_KEY APPLE_SIGNIN_KEY_ID APPLE_SIGNIN_PRIVATE_KEY POSTHOG_PROJECT_TOKEN"
PUBLIC_ID_KEYS="GOOGLE_ID APPLE_ID APPLE_APP_APPLE_ID"

# Last assignment wins, as dotenv does; strip "export " and surrounding quotes.
get() {
  awk -v k="$2" '
    { sub(/^[[:space:]]*export[[:space:]]+/, "") }
    index($0, k "=") == 1 { v = substr($0, length(k) + 2); found = 1 }
    END {
      if (!found) { print "\001unset"; exit }
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", v)
      if (v ~ /^".*"$/ || v ~ /^'"'"'.*'"'"'$/) v = substr(v, 2, length(v) - 2)
      print v
    }' "$1"
}
show() { [ "$1" = $'\001unset' ] && echo "(unset)" || echo "$1"; }
presence() { [ "$1" = $'\001unset' ] || [ -z "$1" ] && echo "unset" || echo "set"; }

diffs=0
echo "Settings that differ between dev and prod"
echo "----------------------------------------------"
for k in $VALUE_KEYS $PUBLIC_ID_KEYS; do
  d="$(get "$DEV_FILE" "$k")"; p="$(get "$PROD_FILE" "$k")"
  if [ "$d" != "$p" ]; then printf '%-36s dev=%s | prod=%s\n' "$k" "$(show "$d")" "$(show "$p")"; diffs=$((diffs+1)); fi
done
for k in $PRESENCE_KEYS; do
  d="$(presence "$(get "$DEV_FILE" "$k")")"; p="$(presence "$(get "$PROD_FILE" "$k")")"
  if [ "$d" != "$p" ]; then printf '%-36s dev=%s | prod=%s\n' "$k" "$d" "$p"; diffs=$((diffs+1)); fi
done
names() { sed -nE 's/^[[:space:]]*(export[[:space:]]+)?([A-Za-z_][A-Za-z0-9_]*)=.*/\2/p' "$1" | sort -u; }
only_dev="$(comm -23 <(names "$DEV_FILE") <(names "$PROD_FILE") | tr '\n' ' ')"
only_prod="$(comm -13 <(names "$DEV_FILE") <(names "$PROD_FILE") | tr '\n' ' ')"
echo
echo "Only in dev:  ${only_dev:-(none)}"
echo "Only in prod: ${only_prod:-(none)}"
echo
echo "$diffs known settings differ."
