function stripHtmlLite(html: string): string {
  if (!html) return '';
  return html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const GENERIC_STORY_TITLE_RE =
  /^(untitled memory|thought|quick capture|quick note|a note|note|memory|untitled|new memory|my thought|a passing thought|voice note|photo note|journal entry)\.?$/i;

function titleFromPlainFallbackStory(plain: string): string {
  const cleaned = plain.replace(/\s+/g, ' ').trim();
  if (!cleaned) return 'Untitled memory';
  const max = 72;
  let slice = cleaned.length <= max ? cleaned : cleaned.slice(0, max);
  if (cleaned.length > max) {
    const lastSpace = slice.lastIndexOf(' ');
    if (lastSpace > 24) slice = slice.slice(0, lastSpace);
    slice = `${slice}…`;
  }
  return slice.charAt(0).toUpperCase() + slice.slice(1);
}

function normalizeGeneratedStoryTitle(
  raw: string,
  plainContext: string,
): string {
  let title = (raw || '').trim();
  title = title.replace(/^["']|["']$/g, '');
  title = title.replace(/\n.*$/s, '');
  title = title.replace(/^title\s*:\s*/i, '').trim();
  if (title.length < 2 || GENERIC_STORY_TITLE_RE.test(title)) {
    return titleFromPlainFallbackStory(plainContext);
  }
  const max = 80;
  if (title.length > max) {
    title = title.slice(0, max);
    const lastSpace = title.lastIndexOf(' ');
    if (lastSpace > 32) title = title.slice(0, lastSpace);
    title = `${title}…`;
  }
  return title;
}

