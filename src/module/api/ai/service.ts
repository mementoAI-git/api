/**
 * Only Gemini can read attachments, so when it fails the member should hear that plainly,
 * not a generic server error, and know the message didn't go through.
 */
export async function readAttachments<T>(send: () => Promise<T>): Promise<T> {
  try {
    return await send();
  } catch (error) {
    logger.error(error, 'Gemini could not read a chat attachment');
    throw new ServiceUnavailableException(
      'Memento can’t read attachments right now, so your message wasn’t sent. Please try again shortly.',
    );
  }
}

function isTranscribableMime(type: string): boolean {
  const base = uploadMimeBaseType(type);
  if (base.startsWith('audio/')) return true;
  /** WebM voice notes are often stored as video/webm (browser / Cloudinary resource type). */
  if (base === 'video/webm') return true;
  return false;
}

export async function transcribeAudio(input: TranscriptionInput) {
  const file =
    input.kind === 'stored' ? await File.findById(input.fileId) : null;
  if (input.kind === 'stored' && !file) {
    throw new NotFoundException('File not found');
  }
  if (file && !isTranscribableMime(file.type)) {
    throw new NotFoundException('Invalid file type ');
  }

  if (file && !isEmpty(file.transcription)) {
    return {message: 'Transcription successful', data: file.transcription};
  }

  const textOnly = input.kind === 'recording';
  const prompt = prompts.createTranscriptionPrompt(textOnly);
  const transcriptionPromptVersion = getPromptVersion('transcription');
  void recordAiMetric({
    event: 'prompt_version_used',
    task: 'transcription',
    endpoint: '/ai/transcribe-audio',
    prompt_version: transcriptionPromptVersion,
  });
  const processedFile =
    input.kind === 'recording'
      ? {
          inlineData: {
            mimeType: input.mimeType,
            data: input.file.buffer.toString('base64'),
          },
        }
      : await processFile(file);
  if (!processedFile) {
    throw new BadRequestException(
      'Could not load this recording from storage for transcription.',
    );
  }

  const result = await transcribeWithConfiguredAsr({
    transcriptionPrompt: prompt,
    textOnly,
    processedFilePart: processedFile,
  });
  void recordAiMetric({
    event: 'ai_route',
    task: 'transcription',
    endpoint: '/ai/transcribe-audio',
    provider: result.provider,
    model: result.model,
    used_fallback: result.usedFallback,
    fallback_count: result.usedFallback ? 1 : 0,
    token_usage: result.tokenUsage,
    metadata: {architecture: 'phase1_asr_abstraction_with_fallback'},
  });

  if (shouldRunAsrShadow()) {
    void (async () => {
      try {
        const shadow = await transcribeWithShadowProvider({
          transcriptionPrompt: prompt,
          textOnly,
          processedFilePart: processedFile,
        });
        if (!shadow) return;
        const primaryShape = getTranscriptionSummaryShape(result.data);
        const shadowShape = getTranscriptionSummaryShape(shadow.data);
        void recordAiMetric({
          event: 'asr_shadow_compare',
          task: 'transcription',
          endpoint: '/ai/transcribe-audio',
          provider: shadow.provider,
          model: shadow.model,
          duration_ms: shadow.durationMs,
          token_usage: shadow.tokenUsage,
          metadata: {
            primaryProvider: result.provider,
            primaryModel: result.model,
            primaryTextLength: primaryShape.textLength,
            shadowTextLength: shadowShape.textLength,
            primarySegmentCount: primaryShape.segmentCount,
            shadowSegmentCount: shadowShape.segmentCount,
            textLengthDelta: shadowShape.textLength - primaryShape.textLength,
            segmentCountDelta:
              shadowShape.segmentCount - primaryShape.segmentCount,
          },
        });
      } catch (shadowError) {
        void recordAiMetric({
          event: 'asr_shadow_error',
          task: 'transcription',
          endpoint: '/ai/transcribe-audio',
          error_message: (shadowError as Error)?.message,
        });
      }
    })();
  }

  if (file) await file.updateOne({transcription: result.data});
  return {message: 'Transcription successful', data: result.data};
}

export async function startConversation(
  payload: IStartMemory,
  user_id: string,
) {
  const requestStart = Date.now();
  const userBackoffRemaining = getUserBackoffRemainingMs(user_id);
  if (userBackoffRemaining > 0) {
    void recordAiMetric({
      event: 'user_backoff_active',
      task: 'chat_bootstrap',
      endpoint: '/ai/conversation/new',
      user: user_id,
      metadata: {remainingMs: userBackoffRemaining},
    });
  }
  let prompt = null;
  const user = await User.findById(user_id);
  if (!user) {
    throw new NotFoundException('User not found');
  }

  if (!isEmpty(payload.prompt_id)) {
    prompt = await Prompt.findOne({
      _id: payload.prompt_id,
      ...buildPromptOwnershipScope(user_id),
    });
  }

  // Single-conversation: reuse existing primary conversation if it exists
  let memory = null;
  if (user.primary_conversation_id) {
    memory = await Memory.findById(user.primary_conversation_id);
  }

  // Create the primary conversation if it doesn't exist yet
  if (!memory) {
    memory = await Memory.create({
      title: null,
      user: user_id,
      type: 'conversation',
      status: 'save',
      message_count: 0,
      last_active: dayjs().toDate(),
    });
    await User.findByIdAndUpdate(user_id, {primary_conversation_id: memory.id});
  }

  // Load recent message history for context
  const recentMessages = await Message.find({user: user_id, memory: memory.id})
    .sort({created_at: -1})
    .limit(25);
  const history = recentMessages.reverse();

  const sessionTurnCount = getSessionTurnCount(history);
  const systemInstruction = await prompts.createSystemContextWithPrompt(
    user,
    prompt,
    memory.id,
    sessionTurnCount,
    {digitalMindName: payload.digitalMindName},
  );
  const chatBootstrapPromptVersion = getPromptVersion('chat_bootstrap');
  void recordAiMetric({
    event: 'prompt_version_used',
    task: 'chat_bootstrap',
    endpoint: '/ai/conversation/new',
    user: user_id,
    prompt_version: chatBootstrapPromptVersion,
  });
  const userText = (payload.text ?? '').trim();
  const hasAttachments = !isEmpty(payload?.attachments);

  // The app opens the conversation first and sends the message through
  // /ai/prompt (streamed). With nothing to say yet, just hand back the
  // conversation instead of rejecting the request.
  if (!userText && !hasAttachments) {
    return {
      message: 'Conversation ready',
      data: {response: '', memory_id: memory.id},
    };
  }

  const content: PartListUnion = [];
  if (userText) {
    content.push(userText);
  }

  if (hasAttachments) {
    const chat = gemini.chats.create({
      model: GEMINI_MODEL,
      config: {systemInstruction},
      history: createChatHistory(history),
    });
    const result = await processFiles(payload.attachments);
    content.push(...result);
    if (content.length === 0) {
      throw new BadRequestException(
        'Could not process the attached file(s). Please try re-uploading.',
      );
    }
    const response = await readAttachments(() =>
      chat.sendMessage({message: content}),
    );
    const responseText = sanitizeMementoText(response.text ?? '').trim();
    const now = dayjs();
    await Message.insertMany([
      {
        user: user_id,
        memory: memory.id,
        role: 'user',
        attatchments: payload?.attachments || [],
        text: payload?.text,
        created_at: now.toDate(),
      },
      {
        user: user_id,
        memory: memory.id,
        role: 'ai',
        server_completed: Boolean(responseText),
        text: responseText,
        created_at: now.add(1, 'second').toDate(),
      },
    ]);
    await Memory.findByIdAndUpdate(memory.id, {
      $inc: {message_count: 2},
      $set: {last_active: now.toDate()},
    });
    await conversationPersisted(user_id, memory.id, 'text');
    void queueMemorySearch(user_id, memory.id);
    if (isEmpty(memory.title)) {
      void updateMemoryTitle(memory.id, payload.text, responseText);
    }
    if (isSignificantMessage(payload.text)) {
      addToInsightsBuffer(user_id, memory.id, payload.text, responseText).catch(
        error => {
          console.error('Error queueing insights extraction:', error);
        },
      );
    }
    void updateStreak(user_id);
    return {
      data: {response: responseText, memory_id: memory.id},
      message: 'Conversation started successfully',
    };
  }

  let responseText = '';
  if (groqClient.isConfigured()) {
    const historyMessages = createChatHistory(history).map(message => ({
      role: message.role === 'model' ? 'assistant' : 'user',
      content: message.parts?.[0]?.text || '',
    })) as GroqMessage[];

    const chatMessages = buildGroqBoundedMessages({
      systemInstruction,
      history: historyMessages,
      userText: payload.text,
    });
    const groqModels = getGroqModelsForPrompt(payload.text);

    try {
      const {text, effectiveModel, usedFallback, tokenUsage} =
        await generateTextWithGroqFallback({
          messages: chatMessages,
          temperature: 0.7,
          timeoutMs: 15_000,
          primaryModel: groqModels.primaryModel,
          fallbackModel: groqModels.fallbackModel,
        });
      responseText = text;
      console.log('AI routing', {
        task: 'chat_bootstrap',
        provider: 'groq',
        effectiveModel,
        usedFallback,
        fastMode: groqModels.fastMode,
        durationMs: Date.now() - requestStart,
      });
      void recordAiMetric({
        event: 'ai_route',
        task: 'chat_bootstrap',
        endpoint: '/ai/conversation/new',
        provider: 'groq',
        model: effectiveModel,
        user: user_id,
        memory: String(memory.id),
        used_fallback: usedFallback,
        duration_ms: Date.now() - requestStart,
        fast_mode: groqModels.fastMode,
        token_usage: tokenUsage,
      });
    } catch (error) {
      if (isProviderRateLimited(error)) setUserBackoffWindow(user_id);
      console.error('AI routing fallback', {
        task: 'chat_bootstrap',
        from: 'groq',
        to: 'gemini',
        reason: (error as Error)?.message,
      });
    }
  }
  if (isEmpty(responseText)) {
    const chat = gemini.chats.create({
      model: GEMINI_MODEL,
      config: {systemInstruction},
      history: createChatHistory(history),
    });
    try {
      const messageContent: PartListUnion =
        content.length > 0 ? content : [userText || 'Hello'];
      const response = await chat.sendMessage({message: messageContent});
      responseText = response.text;
      console.log('AI routing', {
        task: 'chat_bootstrap',
        provider: 'gemini',
        reason: 'groq_failed_or_not_configured',
        durationMs: Date.now() - requestStart,
      });
      void recordAiMetric({
        event: 'ai_route',
        task: 'chat_bootstrap',
        endpoint: '/ai/conversation/new',
        provider: 'gemini',
        model: GEMINI_MODEL,
        user: user_id,
        memory: String(memory.id),
        duration_ms: Date.now() - requestStart,
        token_usage: {
          prompt_tokens: response.usageMetadata?.promptTokenCount,
          completion_tokens: response.usageMetadata?.candidatesTokenCount,
          total_tokens: response.usageMetadata?.totalTokenCount,
        },
      });
    } catch (error) {
      if (isProviderRateLimited(error)) setUserBackoffWindow(user_id);
      console.error('AI routing fallback', {
        task: 'chat_bootstrap',
        from: 'gemini',
        to: 'openrouter',
        reason: (error as Error)?.message,
      });
    }
  }
  if (
    isEmpty(responseText) &&
    OPENROUTER_CRITICAL_ENABLED &&
    isNonStreamingProviderFallbackConfigured()
  ) {
    const historyMessages = createChatHistory(history).map(message => ({
      role: message.role === 'model' ? 'assistant' : 'user',
      content: message.parts?.[0]?.text || '',
    })) as OpenRouterMessage[];
    const chatMessages: OpenRouterMessage[] = [
      {role: 'system', content: systemInstruction},
      ...historyMessages,
      {role: 'user', content: payload.text},
    ];
    try {
      const {text, provider, effectiveModel, usedFallback, tokenUsage} =
        await generateTextWithProviderFallback({
          task: 'chat_bootstrap',
          messages: chatMessages,
          temperature: 0.7,
        });
      responseText = text;
      console.log('AI routing', {
        task: 'chat_bootstrap',
        provider,
        effectiveModel,
        usedFallback,
        durationMs: Date.now() - requestStart,
      });
      void recordAiMetric({
        event: 'ai_route',
        task: 'chat_bootstrap',
        endpoint: '/ai/conversation/new',
        provider,
        model: effectiveModel,
        user: user_id,
        memory: String(memory.id),
        used_fallback: usedFallback,
        duration_ms: Date.now() - requestStart,
        token_usage: tokenUsage,
      });
    } catch (error) {
      if (isProviderRateLimited(error)) setUserBackoffWindow(user_id);
      throw error;
    }
  }

  responseText = sanitizeMementoText(responseText).trim();

  const now = dayjs();
  await Message.insertMany([
    {
      user: user_id,
      memory: memory.id,
      role: 'user',
      attatchments: payload?.attachments || [],
      text: payload?.text,
      created_at: now.toDate(),
    },
    {
      user: user_id,
      memory: memory.id,
      role: 'ai',
      server_completed: Boolean(responseText),
      text: responseText,
      created_at: now.add(1, 'second').toDate(),
    },
  ]);

  await Memory.findByIdAndUpdate(memory.id, {
    $inc: {message_count: 2},
    $set: {last_active: now.toDate()},
  });
  await conversationPersisted(user_id, memory.id, 'text');
  void queueMemorySearch(user_id, memory.id);

  if (isEmpty(memory.title)) {
    void updateMemoryTitle(memory.id, payload.text, responseText);
  }

  if (isSignificantMessage(payload.text)) {
    addToInsightsBuffer(user_id, memory.id, payload.text, responseText).catch(
      error => {
        console.error('Error queueing insights extraction:', error);
      },
    );
  }

  void updateStreak(user_id);

  return {
    data: {response: responseText, memory_id: memory.id},
    message: 'Conversation started successfully',
  };
}

/**
 * Resolve the Gemini voiceName to embed in a Live session constraint.
 * Accepts the user-facing persona name (e.g. 'denver') OR the raw Gemini
 * voice name (e.g. 'fenrir') - whichever is stored in chat_voice.
 * Falls back to Denver (Fenrir) if nothing matches.
 */
function resolveGeminiVoiceName(
  chatVoice: string | undefined,
  chatVoiceProvider: string | undefined,
): {voiceName: string; voiceId: string} {
  const DEFAULT = GEMINI_LIVE_VOICE_CATALOG[0]; // Denver / Fenrir
  if (!chatVoice || (chatVoiceProvider && chatVoiceProvider !== 'gemini')) {
    return {voiceName: DEFAULT.voiceName, voiceId: DEFAULT.id};
  }
  const input = chatVoice.toLowerCase();
  const match = GEMINI_LIVE_VOICE_CATALOG.find(
    v =>
      v.id === input || // persona name  e.g. 'denver'
      v.alias === input || // raw gemini name e.g. 'fenrir'
      v.voiceName.toLowerCase() === input, // also catches full capitalised form
  );
  return match
    ? {voiceName: match.voiceName, voiceId: match.id}
    : {voiceName: DEFAULT.voiceName, voiceId: DEFAULT.id};
}

export async function createEphemeralToken(
  userId: string,
  memoryId?: string,
  resumeHandle?: string,
  client: {
    connectionPersonId?: string;
    connectionSharedSpace?: boolean;
    connectionShareInputs?: boolean;
    deviceModel?: string;
    digitalMindName?: string;
    memoryTool?: boolean;
    callActions?: boolean;
    serverTools?: boolean;
    screenControl?: boolean;
    screenFields?: boolean;
    /** The device's IANA time zone, validated. */
    timeZone?: string;
    timer?: StepTimer;
  } = {},
) {
  const timer = client.timer ?? new StepTimer();
  // Resolve the user with profile and voice preferences
  const user = await timer.time('user', () => User.findById(userId));
  if (!user) {
    throw new NotFoundException('User not found');
  }

  const {voiceName, voiceId} = resolveGeminiVoiceName(
    user.chat_voice ?? undefined,
    user.chat_voice_provider ?? undefined,
  );

  const memoryTool = !client.connectionPersonId && client.memoryTool === true;
  const callActions = !client.connectionPersonId && client.callActions === true;
  const serverTools = !client.connectionPersonId && client.serverTools === true;
  const screenControl =
    !client.connectionPersonId && client.screenControl === true;
  const screenFields = screenControl && client.screenFields === true;
  const voiceContext = client.connectionPersonId
    ? await connectionVoice.prepare(
        client.connectionPersonId,
        userId,
        client.connectionSharedSpace,
        client.connectionShareInputs,
      )
    : await voiceSessionContextFor(user, memoryId, {
        memoryTool,
        callActions,
        serverTools,
        screenControl,
        screenFields,
        timeZone: client.timeZone,
        digitalMindName: client.digitalMindName,
        timer,
        resuming: Boolean(resumeHandle),
      });

  const expireTime = dayjs().add(30, 'minute').toDate();
  // 10 min gives mobile clients a realistic window to establish the WebSocket
  // even on slow networks or after a brief app backgrounding.
  const newSessionExpireTime = dayjs().add(10, 'minutes').toDate();

  // Same user, same arm: reconnects within a call keep their turn detection.
  const turnDetection = chooseVoiceTurnDetection(userId, VOICE_TURN_AB_PERCENT);

  const live = buildLiveSessionDescriptor(GEMINI_LIVE_MODEL, {
    id: voiceId,
    name: voiceName,
    provider: 'gemini',
  });

  const token = await timer.time('token', () =>
    geminiAuthClient.authTokens.create({
      config: {
        uses: 1,
        // No lockAdditionalFields: every field below is locked as-is. Passing []
        // makes the SDK send a field mask built from the config, which includes
        // `tools.0`; Gemini rejects that ("field_mask is invalid for
        // BidiGenerateContentSetup") and every voice call fails.
        expireTime: expireTime.toISOString(),
        newSessionExpireTime: newSessionExpireTime.toISOString(),
        liveConnectConstraints: {
          model: live.model,
          // Constraints lock every LiveConnectConfig field. Client config is
          // ignored, so all voice context must be built here.
          config: buildLiveConnectConfig(
            live.voice.name,
            voiceContext.systemInstruction,
            client.connectionPersonId ? undefined : resumeHandle,
            {memoryTool, callActions, serverTools, screenControl, screenFields},
            turnDetection,
          ),
        },
        httpOptions: {
          apiVersion: 'v1alpha',
        },
      },
    }),
  );

  void recordAiMetric({
    event: 'prompt_version_used',
    task: 'voice_session',
    endpoint: '/ai/ephemeral-token',
    user: userId,
    prompt_version: VOICE_PROMPT_VERSION,
  });

  return {
    message: 'Ephemeral token created successfully',
    data: {
      token: token.name,
      connectionSessionId:
        'connectionSessionId' in voiceContext
          ? voiceContext.connectionSessionId
          : undefined,
      expiresAt: expireTime.toISOString(),
      voice: live.voice,
      live,
      greetingInstruction: voiceContext.greetingInstruction,
      memoryId: voiceContext.memoryId ?? null,
      promptVersion: VOICE_PROMPT_VERSION,
      tools: [
        ...(memoryTool ? [SEARCH_MEMORIES_TOOL_NAME] : []),
        ...(callActions ? CALL_ACTION_TOOL_NAMES : []),
        ...(serverTools ? SERVER_TOOL_NAMES : []),
        ...(screenControl ? SCREEN_CONTROL_TOOL_NAMES : []),
        ...(screenFields ? SCREEN_FIELDS_TOOL_NAMES : []),
      ],
      // The app forwards these to POST /ai/voice/tools/:name.
      serverTools: serverTools ? SERVER_TOOL_NAMES : [],
      speakerFullDuplex: allowsSpeakerFullDuplex(client.deviceModel),
      turnDetection: describeVoiceTurnDetection(turnDetection),
    },
  };
}

export async function autogenerateTags(payload: {
  title?: string;
  body?: string;
}) {
  const requestStart = Date.now();
  const title = (payload.title ?? '').trim();
  const body = (payload.body ?? '').trim();
  const prompt = prompts.buildTagsPrompt();
  const tagsPromptVersion = getPromptVersion('tags_generate');
  void recordAiMetric({
    event: 'prompt_version_used',
    task: 'tags_generate',
    endpoint: '/ai/generate-tags',
    prompt_version: tagsPromptVersion,
  });

  const userContent = `TITLE:\n${title || '(none)'}\n\nBODY:\n${body || '(none)'}`;
  const tagMessages: OpenRouterMessage[] = [
    {role: 'system', content: prompt},
    {role: 'user', content: userContent},
  ];
  const geminiContents = createUserContent([prompt, {text: userContent}]);

  let rawText = '';

  const runGeminiTags = async (reason: string) => {
    const response = await gemini.models.generateContent({
      model: GEMINI_MODEL,
      contents: geminiContents,
    });
    rawText = response.text ?? '';
    console.log('AI routing', {
      task: 'tags_generate',
      provider: 'gemini',
      reason,
      durationMs: Date.now() - requestStart,
    });
    void recordAiMetric({
      event: 'ai_route',
      task: 'tags_generate',
      endpoint: '/ai/generate-tags',
      provider: 'gemini',
      model: GEMINI_MODEL,
      duration_ms: Date.now() - requestStart,
      token_usage: {
        prompt_tokens: response.usageMetadata?.promptTokenCount,
        completion_tokens: response.usageMetadata?.candidatesTokenCount,
        total_tokens: response.usageMetadata?.totalTokenCount,
      },
      metadata: {reason},
    });
  };

  try {
    if (isNonStreamingProviderFallbackConfigured()) {
      try {
        const {text, provider, effectiveModel, usedFallback, tokenUsage} =
          await generateTextWithProviderFallback({
            task: 'tags_generate',
            messages: tagMessages,
            temperature: 0.2,
          });
        rawText = text;
        console.log('AI routing', {
          task: 'tags_generate',
          provider,
          effectiveModel,
          usedFallback,
          durationMs: Date.now() - requestStart,
        });
        void recordAiMetric({
          event: 'ai_route',
          task: 'tags_generate',
          endpoint: '/ai/generate-tags',
          provider,
          model: effectiveModel,
          used_fallback: usedFallback,
          duration_ms: Date.now() - requestStart,
          token_usage: tokenUsage,
        });
      } catch (orError) {
        console.error(
          orError,
          'autogenerateTags: provider fallback failed, trying Gemini',
        );
        void recordAiMetric({
          event: 'ai_route',
          task: 'tags_generate',
          endpoint: '/ai/generate-tags',
          provider: 'provider_fallback',
          duration_ms: Date.now() - requestStart,
          metadata: {
            error: String((orError as Error)?.message),
            stage: 'provider_fallback_failed',
          },
        });
        await runGeminiTags('provider_fallback_failed');
      }
    } else {
      await runGeminiTags('no_provider_fallback');
    }
  } catch (error) {
    console.error(
      error,
      'autogenerateTags: all AI providers failed; using heuristic tags',
    );
    void recordAiMetric({
      event: 'ai_route',
      task: 'tags_generate',
      endpoint: '/ai/generate-tags',
      provider: 'none',
      duration_ms: Date.now() - requestStart,
      metadata: {
        error: String((error as Error)?.message),
        stage: 'heuristic_only',
      },
    });
    rawText = '';
  }

  const parsed = extractJson(rawText);
  const validated = tagsOutputSchema.safeParse(parsed);
  const rawTags = validated.success ? validated.data.tags : [];
  const normalizedTags = ensureStoryAutogenTagCount(
    normalizeAutogeneratedStoryTags(rawTags),
    `${title}\n${body}`,
  );

  return {
    data: {tags: normalizedTags},
    message: 'Tags generated successfully',
  };
}

function stripHtmlLite(html: string): string {
  if (!html) return '';
  return html
    .replace(/<[^>]+>/g, ' ')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const GENERIC_STORY_TITLE_RE =
  /^(untitled memory|thought|quick capture|quick note|a note|note|memory|untitled|new memory|my thought|a passing thought|voice note|photo note|journal entry)\.?$/i;

function titleFromPlainFallbackStory(plain: string): string {
  const cleaned = plain.replace(/\s+/g, ' ').trim();
  if (!cleaned) return 'Untitled memory';
  const max = 72;
  let slice = cleaned.length <= max ? cleaned : cleaned.slice(0, max);
  if (cleaned.length > max) {
    const lastSpace = slice.lastIndexOf(' ');
    if (lastSpace > 24) slice = slice.slice(0, lastSpace);
    slice = `${slice}…`;
  }
  return slice.charAt(0).toUpperCase() + slice.slice(1);
}

function normalizeGeneratedStoryTitle(
  raw: string,
  plainContext: string,
): string {
  let title = (raw || '').trim();
  title = title.replace(/^["']|["']$/g, '');
  title = title.replace(/\n.*$/s, '');
  title = title.replace(/^title\s*:\s*/i, '').trim();
  if (title.length < 2 || GENERIC_STORY_TITLE_RE.test(title)) {
    return titleFromPlainFallbackStory(plainContext);
  }
  const max = 80;
  if (title.length > max) {
    title = title.slice(0, max);
    const lastSpace = title.lastIndexOf(' ');
    if (lastSpace > 32) title = title.slice(0, lastSpace);
    title = `${title}…`;
  }
  return title;
}

export async function autogenerateStoryTitle(payload: {
  title?: string;
  body?: string;
}) {
  const requestStart = Date.now();
  const hint = (payload.title ?? '').trim();
  const plain = stripHtmlLite(payload.body ?? '');
  const system = prompts.buildStoryMemoryTitlePrompt();
  const userBlock = plain
    ? `STORY TEXT:\n${plain}${
        hint ? `\n\nDRAFT TITLE (optional - refine if it helps):\n${hint}` : ''
      }`
    : `DRAFT TITLE TO IMPROVE:\n${hint}`;

  const titleMessages: OpenRouterMessage[] = [
    {role: 'system', content: system},
    {role: 'user', content: userBlock},
  ];
  const geminiContents = createUserContent(`${system}\n\n${userBlock}`);

  let rawText = '';

  const runGeminiTitle = async (reason: string) => {
    const response = await gemini.models.generateContent({
      model: GEMINI_MODEL,
      contents: geminiContents,
    });
    rawText = response.text ?? '';
    void recordAiMetric({
      event: 'ai_route',
      task: 'story_title_generate',
      endpoint: '/ai/generate-story-title',
      provider: 'gemini',
      model: GEMINI_MODEL,
      duration_ms: Date.now() - requestStart,
      token_usage: {
        prompt_tokens: response.usageMetadata?.promptTokenCount,
        completion_tokens: response.usageMetadata?.candidatesTokenCount,
        total_tokens: response.usageMetadata?.totalTokenCount,
      },
      metadata: {reason},
    });
  };

  try {
    if (isNonStreamingProviderFallbackConfigured()) {
      try {
        const {text, provider, effectiveModel, usedFallback, tokenUsage} =
          await generateTextWithProviderFallback({
            task: 'title_generate',
            messages: titleMessages,
            temperature: 0.35,
          });
        rawText = text;
        void recordAiMetric({
          event: 'ai_route',
          task: 'story_title_generate',
          endpoint: '/ai/generate-story-title',
          provider,
          model: effectiveModel,
          used_fallback: usedFallback,
          duration_ms: Date.now() - requestStart,
          token_usage: tokenUsage,
        });
      } catch (orError) {
        console.error(
          orError,
          'autogenerateStoryTitle: provider fallback failed, trying Gemini',
        );
        void recordAiMetric({
          event: 'ai_route',
          task: 'story_title_generate',
          endpoint: '/ai/generate-story-title',
          provider: 'provider_fallback',
          duration_ms: Date.now() - requestStart,
          metadata: {
            error: String((orError as Error)?.message),
            stage: 'provider_fallback_failed',
          },
        });
        await runGeminiTitle('provider_fallback_failed');
      }
    } else {
      await runGeminiTitle('no_provider_fallback');
    }
  } catch (error) {
    console.error(
      error,
      'autogenerateStoryTitle: all AI providers failed; heuristic title',
    );
    void recordAiMetric({
      event: 'ai_route',
      task: 'story_title_generate',
      endpoint: '/ai/generate-story-title',
      provider: 'none',
      duration_ms: Date.now() - requestStart,
      metadata: {
        error: String((error as Error)?.message),
        stage: 'heuristic_only',
      },
    });
    rawText = '';
  }

  const finalTitle = normalizeGeneratedStoryTitle(rawText, plain || hint);

  return {
    data: {title: finalTitle},
    message: 'Title suggested successfully',
  };
}

