import {PREDEFINED_STORY_TAGS} from './constant';

export const STORY_AUTOGEN_TAG_MIN = 2;
export const STORY_AUTOGEN_TAG_MAX = 3;

const ALLOWED = new Set<string>(PREDEFINED_STORY_TAGS);

/** Instructions appended to prompts that emit story tags (modal + quick-capture enrichment). */
export function buildTagsJsonInstructions(): string {
  const list = PREDEFINED_STORY_TAGS.join(', ');
  return `Tags: Include between ${STORY_AUTOGEN_TAG_MIN} and ${STORY_AUTOGEN_TAG_MAX} tags in the "tags" array. Each tag MUST be copied exactly from this allowed list (lowercase, no extras): ${list}. No duplicates. No tags outside this list.`;
}

/** Keep only allowed predefined tags, dedupe, cap at max. */
export function normalizeAutogeneratedStoryTags(tags: unknown[]): string[] {
  const out: string[] = [];
  for (const t of tags) {
    if (typeof t !== 'string') continue;
    const s = t.trim().toLowerCase();
    if (!ALLOWED.has(s) || out.includes(s)) continue;
    out.push(s);
    if (out.length >= STORY_AUTOGEN_TAG_MAX) break;
  }
  return out;
}

/**
 * Ensure 2–3 allowed tags; pad from context heuristics, then generic fallbacks.
 */
export function ensureStoryAutogenTagCount(
  tags: string[],
  contextPlain: string,
): string[] {
  const result = [...tags];
  const text = contextPlain.toLowerCase();

  if (result.length >= STORY_AUTOGEN_TAG_MIN) {
    return result.slice(0, STORY_AUTOGEN_TAG_MAX);
  }

  const candidates = [...PREDEFINED_STORY_TAGS].filter(
    t => !result.includes(t),
  );
  candidates.sort((a, b) => {
    const score = (s: string) => (text.includes(s) ? 1 : 0);
    return score(b) - score(a);
  });

  for (const c of candidates) {
    if (result.length >= STORY_AUTOGEN_TAG_MIN) break;
    result.push(c);
  }

  const fallbacks: string[] = ['reflection', 'growth'];
  for (const f of fallbacks) {
    if (result.length >= STORY_AUTOGEN_TAG_MIN) break;
    if (!result.includes(f)) result.push(f);
  }

  return result.slice(0, STORY_AUTOGEN_TAG_MAX);
}
